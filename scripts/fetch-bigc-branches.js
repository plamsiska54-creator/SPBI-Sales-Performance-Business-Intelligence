var https = require('https');
var fs = require('fs');
var path = require('path');

var URL = 'https://corporate.bigc.co.th/include/markers';
var OUTPUT = path.join(__dirname, '..', 'js', 'bigc-branches.js');

function fetch(url) {
  return new Promise(function(resolve, reject) {
    https.get(url, { headers: { 'Accept': 'application/json' } }, function(res) {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        return fetch(res.headers.location).then(resolve, reject);
      }
      if (res.statusCode !== 200) {
        return reject(new Error('HTTP ' + res.statusCode));
      }
      var chunks = [];
      res.on('data', function(c) { chunks.push(c); });
      res.on('end', function() { resolve(Buffer.concat(chunks).toString('utf8')); });
      res.on('error', reject);
    }).on('error', reject);
  });
}

function extractProvince(address) {
  if (!address) return '';
  if (/กรุงเทพ/.test(address)) return 'กรุงเทพมหานคร';
  var m = address.match(/จังหวัด\s*([^\s\d,]+)/);
  if (m) return m[1];
  return '';
}

function cleanName(name) {
  if (!name) return '';
  return name.replace(/^\d+\s*\t?\s*/, '').trim();
}

function cleanAddress(addr) {
  if (!addr) return '';
  return addr.replace(/\s{2,}/g, ' ').trim();
}

(async function() {
  console.log('Fetching branches from', URL, '...');
  var raw = await fetch(URL);
  var branches = JSON.parse(raw);
  console.log('Fetched', branches.length, 'branches');

  var esc = function(s) {
    return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, ' ').replace(/\r/g, '').replace(/\t/g, ' ');
  };

  var rows = branches.map(function(b) {
    var name = cleanName(b.name || '');
    var addr = cleanAddress(b.address || '');
    var province = extractProvince(addr);
    var tel = (b.tel && b.tel !== '-') ? b.tel : (b.mobile && b.mobile !== '-') ? b.mobile : '';
    var typeId = parseInt(b.type_id) || 0;
    var lat = parseFloat(b.lat) || 0;
    var lng = parseFloat(b.lng) || 0;
    return {typeId: typeId, name: name, lat: lat, lng: lng, tel: tel, address: addr, province: province};
  });

  rows.sort(function(a, b) { return a.name.localeCompare(b.name, 'th'); });

  var lines = rows.map(function(r) {
    return '[' + r.typeId + ',"' + esc(r.name) + '",' + r.lat + ',' + r.lng + ',"' + esc(r.tel) + '","' + esc(r.address) + '","' + esc(r.province) + '"]';
  });

  // Format: [typeId, name, lat, lng, tel, address, province]
  // typeId: 1=บิ๊กซี, 3=บิ๊กซี มาร์เก็ต, 4=บิ๊กซี ฟู๊ดเพลส, 5=บิ๊กซีมินิ, 6=ร้านยาเพรียว, 7=บิ๊กซี ดีโป้
  var content = '// Big C Branches — auto-generated by scripts/fetch-bigc-branches.js\n';
  content += '// Format: [typeId, name, lat, lng, tel, address, province]\n';
  content += '// typeId: 1=บิ๊กซี, 3=บิ๊กซี มาร์เก็ต, 4=บิ๊กซี ฟู๊ดเพลส, 5=บิ๊กซีมินิ, 6=ร้านยาเพรียว, 7=บิ๊กซี ดีโป้\n';
  content += 'var BIGC_BRANCHES=[\n' + lines.join(',\n') + '\n];\n';
  fs.writeFileSync(OUTPUT, content, 'utf8');
  console.log('Written', rows.length, 'branches to', OUTPUT);

  // Stats
  var stats = {};
  rows.forEach(function(r) { stats[r.typeId] = (stats[r.typeId] || 0) + 1; });
  console.log('Stats:', JSON.stringify(stats));
})().catch(function(err) {
  console.error('Error:', err.message || err);
  process.exit(1);
});
