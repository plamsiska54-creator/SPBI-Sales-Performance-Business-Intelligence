function _avt_filterTable() {
  var search = (document.getElementById('avtSearch') || {}).value || '';
  search = search.toLowerCase();
  var dateFrom = (document.getElementById('avtDateFrom') || {}).value || '';
  var dateTo   = (document.getElementById('avtDateTo') || {}).value || '';
  var fResult  = (document.getElementById('avtFilterResult') || {}).value || '';
  var fStatus  = (document.getElementById('avtFilterStatus') || {}).value || '';

  // Sort newest first
  var sorted = _avtFilteredData().slice().sort(function(a,b){ return b[0].localeCompare(a[0]); });

  var rows = '';
  sorted.forEach(function(r) {
    // Apply filters
    if (dateFrom && r[0] < dateFrom) return;
    if (dateTo && r[0] > dateTo) return;
    if (fResult && r[5] !== fResult) return;
    if (fStatus && r[7] !== fStatus) return;
    if (search) {
      var haystack = (r[1]+' '+r[2]+' '+r[4]+' '+r[8]).toLowerCase();
      if (haystack.indexOf(search) === -1) return;
    }

    rows += '<tr style="border-bottom:1px solid #f1f5f9">';
    rows += '<td style="padding:8px;white-space:nowrap">'+_avt_fmtDateThai(r[0])+'</td>';
    rows += '<td style="padding:8px;font-family:monospace;font-size:12px">'+r[1]+'</td>';
    rows += '<td style="padding:8px;font-weight:500">'+r[2]+'</td>';
    rows += '<td style="padding:8px">'+r[3]+'</td>';
    rows += '<td style="padding:8px;font-size:12px">'+(r[4] || '-')+'</td>';
    rows += '<td style="padding:8px;text-align:center">'+_avt_resultBadge(r[5])+'</td>';
    rows += '<td style="padding:8px;text-align:center;font-size:12px">'+(r[6] || '-')+'</td>';
    rows += '<td style="padding:8px;text-align:center">'+_avt_statusBadge(r[7])+'</td>';
    rows += '<td style="padding:8px;font-size:12px;color:#64748b;max-width:260px">'+r[8]+'</td>';
    rows += '</tr>';
  });

  if (!rows) {
    rows = '<tr><td colspan="9" style="padding:24px;text-align:center;color:#94a3b8">ไม่พบข้อมูล</td></tr>';
  }

  var tbody = document.getElementById('avtTbody');
  if (tbody) tbody.innerHTML = rows;
}

