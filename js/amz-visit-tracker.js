function _avt_aiAnalysis(data) {
  if (_avtSalesPerson === 'all' || data.length === 0) return '';

  var person = '';
  AMZ_VISIT_SALES.forEach(function(s){ if(s.key === _avtSalesPerson) person = s.name; });
  if (!person) return '';

  var total = data.length;
  var closed = 0, interested = 0, followUp = 0, notInterested = 0, tasting = 0;
  var reasons = {}, results = {}, callDone = 0;
  var stores = {}, dates = {};

  data.forEach(function(r) {
    stores[r[1]] = 1; dates[r[0]] = 1;
    var reason = r[3] || ''; reasons[reason] = (reasons[reason] || 0) + 1;
    var result = r[5] || ''; results[result] = (results[result] || 0) + 1;
    if (r[7] === 'ปิดการขายแล้ว') closed++;
    if (result === 'สนใจ' || result === 'สั่งซื้อแล้ว') interested++;
    if (result === 'ไม่สนใจ') notInterested++;
    if (result === 'ขอชิมเพิ่ม') tasting++;
    if (r[7] === 'ติดตามต่อ') followUp++;
    if (r[6] === 'โทรแล้ว' || r[6] === 'นัดโทรอีกครั้ง') callDone++;
  });

  var uniqueStores = Object.keys(stores).length;
  var uniqueDates = Object.keys(dates).length;
  var conv = total > 0 ? Math.round(closed / total * 1000) / 10 : 0;
  var visitPerDay = uniqueDates > 0 ? Math.round(total / uniqueDates * 10) / 10 : 0;
  var callPct = total > 0 ? Math.round(callDone / total * 100) : 0;

  // Revisit analysis
  var storeVisits = {};
  data.forEach(function(r) {
    storeVisits[r[1]] = (storeVisits[r[1]] || 0) + 1;
  });
  var repeatCount = 0;
  Object.values(storeVisits).forEach(function(v){ if(v > 1) repeatCount++; });
  var revisitPct = uniqueStores > 0 ? Math.round(repeatCount / uniqueStores * 100) : 0;

  // Reason breakdown
  var openNew = reasons['เปิดร้านใหม่'] || 0;
  var trackSales = reasons['ติดตามยอดขาย'] || 0;
  var openNewPct = total > 0 ? Math.round(openNew / total * 100) : 0;
  var trackPct = total > 0 ? Math.round(trackSales / total * 100) : 0;

  // Conversion by reason
  var closedByReason = {};
  data.forEach(function(r) {
    var reason = r[3] || '';
    if (!closedByReason[reason]) closedByReason[reason] = { t: 0, c: 0 };
    closedByReason[reason].t++;
    if (r[7] === 'ปิดการขายแล้ว') closedByReason[reason].c++;
  });

  // Determine strengths and style
  var strengths = [];
  var weaknesses = [];
  var style = '';
  var styleIcon = '';
  var styleColor = '';

  if (conv >= 25) {
    style = 'Closer — เก่งปิดการขาย';
    styleIcon = '🏆'; styleColor = '#16a34a';
    strengths.push('Closing rate สูง ' + conv + '% — เข้าพบแล้วปิดการขายได้ดีมาก');
  } else if (conv >= 15) {
    style = 'Balanced — สมดุลดี';
    styleIcon = '⚖️'; styleColor = '#2563eb';
    strengths.push('Conversion rate อยู่ในระดับดี ' + conv + '%');
  } else {
    style = 'Hunter — เน้นเปิดตลาด';
    styleIcon = '🚀'; styleColor = '#7c3aed';
    strengths.push('เข้าพบลูกค้าจำนวนมาก ' + total + ' ครั้ง ครอบคลุม ' + uniqueStores + ' ร้าน');
  }

  if (revisitPct >= 50) {
    strengths.push('สร้างความสัมพันธ์ดี — กลับเยี่ยมซ้ำ ' + revisitPct + '% ของร้าน (' + repeatCount + '/' + uniqueStores + ')');
  }
  if (tasting >= 10) {
    strengths.push('ใช้กลยุทธ์ให้ชิมสินค้าได้ผล — ลูกค้าขอชิม ' + tasting + ' ครั้ง');
  }
  if (callPct >= 50) {
    strengths.push('โทรติดตามสม่ำเสมอ ' + callPct + '% ของการเข้าพบ');
  }
  if (trackPct >= 30) {
    strengths.push('ดูแลลูกค้าเก่าดี — ติดตามยอดขาย ' + trackPct + '% ของการเข้าพบ');
  }
  if (visitPerDay >= 7) {
    strengths.push('ขยันเข้าพบ เฉลี่ย ' + visitPerDay + ' ร้าน/วัน');
  }
  if (openNew > 0) {
    var openConv = closedByReason['เปิดร้านใหม่'] ? Math.round(closedByReason['เปิดร้านใหม่'].c / closedByReason['เปิดร้านใหม่'].t * 100) : 0;
    if (openConv >= 25) strengths.push('เก่งเปิดร้านใหม่ — ปิดได้ ' + openConv + '% (' + closedByReason['เปิดร้านใหม่'].c + '/' + closedByReason['เปิดร้านใหม่'].t + ')');
  }

  // Weaknesses
  if (conv < 20) weaknesses.push('Conversion ยังต่ำ (' + conv + '%) ควรคัดกรองลูกค้าก่อนเข้าพบ');
  if (callPct < 40) weaknesses.push('บันทึก Call ยังน้อย (' + callPct + '%) ควรบันทึกการโทรติดตามให้ครบ');
  if (trackPct < 10 && openNewPct > 90) weaknesses.push('เน้นเปิดร้านใหม่ ' + openNewPct + '% ควรเพิ่มการติดตามยอดร้านเดิม (upsell)');
  if (revisitPct < 30) weaknesses.push('กลับเยี่ยมซ้ำน้อย (' + revisitPct + '%) ควรติดตามลูกค้าที่สนใจอย่างต่อเนื่อง');
  if (trackSales > 0 && closedByReason['ติดตามยอดขาย']) {
    var trackConv = Math.round(closedByReason['ติดตามยอดขาย'].c / closedByReason['ติดตามยอดขาย'].t * 100);
    if (trackConv < 15) weaknesses.push('ติดตามยอดเก่า conversion แค่ ' + trackConv + '% ควรเตรียม offer ก่อนเข้าพบ');
  }

  // Build HTML
  var h = '<div class="card" style="margin-bottom:16px;border-left:4px solid ' + styleColor + ';background:linear-gradient(135deg,#fffbf5,#fff)">';
  h += '<div style="display:flex;align-items:center;gap:10px;margin-bottom:12px">';
  h += '<span style="font-size:24px">' + styleIcon + '</span>';
  h += '<div>';
  h += '<div style="font-size:15px;font-weight:700;color:#1e293b">AI วิเคราะห์: ' + person + '</div>';
  h += '<div style="font-size:12px;color:' + styleColor + ';font-weight:600">' + style + '</div>';
  h += '</div></div>';

  // Quick stats
  h += '<div style="display:flex;flex-wrap:wrap;gap:8px;margin-bottom:14px">';
  h += '<span style="display:inline-block;padding:4px 12px;border-radius:20px;font-size:11px;font-weight:600;background:#dcfce7;color:#16a34a;border:1px solid #86efac">ปิดขาย ' + closed + '/' + total + ' (' + conv + '%)</span>';
  h += '<span style="display:inline-block;padding:4px 12px;border-radius:20px;font-size:11px;font-weight:600;background:#eff6ff;color:#2563eb;border:1px solid #93c5fd">เยี่ยมซ้ำ ' + revisitPct + '%</span>';
  h += '<span style="display:inline-block;padding:4px 12px;border-radius:20px;font-size:11px;font-weight:600;background:#fff7ed;color:#ea580c;border:1px solid #fdba74">เปิดใหม่ ' + openNewPct + '% / ติดตาม ' + trackPct + '%</span>';
  h += '<span style="display:inline-block;padding:4px 12px;border-radius:20px;font-size:11px;font-weight:600;background:#f5f3ff;color:#7c3aed;border:1px solid #c4b5fd">' + visitPerDay + ' ร้าน/วัน</span>';
  h += '</div>';

  // Strengths
  if (strengths.length > 0) {
    h += '<div style="font-size:13px;font-weight:700;color:#16a34a;margin-bottom:6px">✅ จุดเด่น</div>';
    strengths.forEach(function(s) {
      h += '<div style="font-size:13px;color:#334155;line-height:1.8;padding-left:8px">• ' + s + '</div>';
    });
  }

  // Weaknesses
  if (weaknesses.length > 0) {
    h += '<div style="font-size:13px;font-weight:700;color:#ea580c;margin:10px 0 6px">⚠️ สิ่งที่ควรพัฒนา</div>';
    weaknesses.forEach(function(w) {
      h += '<div style="font-size:13px;color:#64748b;line-height:1.8;padding-left:8px">• ' + w + '</div>';
    });
  }

  h += '</div>';
  return h;
}

