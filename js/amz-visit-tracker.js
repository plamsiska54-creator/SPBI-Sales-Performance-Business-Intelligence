function _avtDateRange() {
  var now = new Date();
  var y = 2026, m = now.getMonth(), d = now.getDate();
  if (_avtPeriod === 'all') return null;
  if (_avtPeriod === 'thismonth') {
    var from = y + '-' + String(m + 1).padStart(2, '0') + '-01';
    var to = y + '-' + String(m + 1).padStart(2, '0') + '-31';
    return [from, to];
  }
  if (_avtPeriod === 'lastmonth') {
    var lm = m === 0 ? 12 : m;
    var ly = m === 0 ? y - 1 : y;
    var from = ly + '-' + String(lm).padStart(2, '0') + '-01';
    var to = ly + '-' + String(lm).padStart(2, '0') + '-31';
    return [from, to];
  }
  if (_avtPeriod === 'q1') return [y + '-01-01', y + '-03-31'];
  if (_avtPeriod === 'q2') return [y + '-04-01', y + '-06-30'];
  if (_avtPeriod === 'q3') return [y + '-07-01', y + '-09-30'];
  if (_avtPeriod === 'q4') return [y + '-10-01', y + '-12-31'];
  return null;
}

