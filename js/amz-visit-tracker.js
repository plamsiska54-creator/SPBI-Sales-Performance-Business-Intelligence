function _avt_fmtDateThai(iso) {
  var thaiMonths = ['ม.ค.','ก.พ.','มี.ค.','เม.ย.','พ.ค.','มิ.ย.','ก.ค.','ส.ค.','ก.ย.','ต.ค.','พ.ย.','ธ.ค.'];
  var d = new Date(iso);
  var day = d.getDate();
  var mon = thaiMonths[d.getMonth()];
  var yr = (d.getFullYear() + 543) % 100;
  return day + ' ' + mon + ' ' + yr;
}

function _avt_computeKPIs(data) {
  var total = data.length;
  var won = 0, followUp = 0, lost = 0;
  var resultMap = {};
  data.forEach(function(r) {
    var st = r[7];
    if (st === 'ปิดการขายแล้ว') won++;
    else if (st === 'ติดตามต่อ' || st === 'รอตัดสินใจ') followUp++;
    else if (st === 'ไม่ปิดการขาย') lost++;
    var res = r[5];
    if (res) resultMap[res] = (resultMap[res] || 0) + 1;
  });
  var convRate = total > 0 ? ((won / total) * 100).toFixed(1) : '0.0';
  return { total: total, won: won, followUp: followUp, lost: lost, open: 0, convRate: convRate, resultMap: resultMap };
}

function _avt_getVisitsPerDay(data) {
  var map = {};
  data.forEach(function(r) { map[r[0]] = (map[r[0]] || 0) + 1; });
  var keys = Object.keys(map).sort();
  return { labels: keys.map(_avt_fmtDateThai), values: keys.map(function(k){return map[k];}) };
}

